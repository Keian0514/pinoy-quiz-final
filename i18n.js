const languageLocales = {
    PILIPINO: "fil",
    ENGLISH: "en",
    ESPANOL: "es",
    JAPANESE: "ja"
};

function translate(key, values = {}) {
    const language = localStorage.getItem("pinoyQuizLanguage") || "ENGLISH";
    const template = translations[language]?.[key] ?? translations.ENGLISH[key] ?? key;

    return template.replace(/\{(\w+)\}/g, (match, name) => values[name] ?? match);
}

function applyLanguage(language, persist = true) {
    const selectedLanguage = Object.hasOwn(translations, language) ? language : "ENGLISH";

    if (persist) {
        localStorage.setItem("pinoyQuizLanguage", selectedLanguage);
    }

    document.documentElement.lang = languageLocales[selectedLanguage];
    document.querySelectorAll("[data-i18n]").forEach((element) => {
        const values = element.dataset.i18nCount ? { count: element.dataset.i18nCount } : {};
        const text = translate(element.dataset.i18n, values);
        if (element instanceof HTMLTitleElement) {
            document.title = text;
        } else {
            element.innerText = text;
        }
    });
    document.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
        element.setAttribute("aria-label", translate(element.dataset.i18nAriaLabel));
    });
    document.querySelectorAll("[data-i18n-title]").forEach((element) => {
        element.title = translate(element.dataset.i18nTitle);
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
        element.placeholder = translate(element.dataset.i18nPlaceholder);
    });
    document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
        element.alt = translate(element.dataset.i18nAlt);
    });

    const languageSelect = document.querySelector("#language-select");
    if (languageSelect) {
        languageSelect.value = selectedLanguage;
    }

    document.dispatchEvent(new CustomEvent("quiz-language-change", {
        detail: { language: selectedLanguage }
    }));
}

const storedLanguage = localStorage.getItem("pinoyQuizLanguage") || "ENGLISH";
const languageSelect = document.querySelector("#language-select");
if (languageSelect) {
    languageSelect.addEventListener("change", () => applyLanguage(languageSelect.value));
}

window.translations = translations;
window.t = translate;
window.applyLanguage = applyLanguage;
applyLanguage(storedLanguage, false);
